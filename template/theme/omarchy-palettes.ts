// The 22 palettes Omarchy ships, read from themes/<name>/colors.toml in
// omacom/omarchy (MIT, Copyright (c) David Heinemeier Hansson; see
// THIRD-PARTY-NOTICES.md). Each colors.toml maps onto Folioh's tokens:
// - page from background, ink from foreground, primary from accent;
// - fills from lighter_background on dark palettes and dark_background on
//   light ones, rules from lighter_background or darker_background; where
//   lighter_background is the page itself (Last Horizon, Solitude), fills and
//   rules are the page moved toward the ink;
// - code blocks from dark_background;
// - charts from accent, green, yellow, magenta and cyan;
// - destructive from red. Where red is not a red, Solitude takes bright_red
//   and Hackerman, Lumon, Lupine, Miasma, Vantablack and White a stock red.
// Secondary ink is the page colour mixed toward the foreground until it reads
// at WCAG AA, and an accent or a red under 4.5:1 on the page is pushed toward
// white or black. Kanagawa takes its blue as primary: its accent is its ink.
// Entries are keyed by `value`: the Rust preset scan reads every quoted id
// under theme/ as a preset id.

