"""First-party kanban plugin: owns the ``kanban:`` docs.yaml key.

The board is git-persisted: the committed YAML is the source of truth.
In the browser, cards can be dragged between columns; moves are stored as a
localStorage overlay keyed to the committed board, and the exports produce
ready-to-commit move commands that close the loop. Columns are loaded from
a cardfile board directory named by ``kanban.source`` — a ``board.yaml``
schema file plus one Markdown file per card under ``cards/``, all versioned
with the project sources. The ``kanban.routes.public`` setting accepts a path
to choose where the board view is published (``"/"`` for the front page).
"""

